import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {chromium} from 'playwright';
import {createRuntime} from './helpers/emitted-runtime.mjs';

const evidence=process.env.H2H_EVIDENCE_DIR||await mkdtemp(join(tmpdir(),'h2h-demo-inbox-'));
await mkdir(evidence,{recursive:true});
const runtime=await createRuntime(), browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
let success=false;
try {
  await page.goto(runtime.origin+'/setup');
  await page.getByLabel('Your name',{exact:true}).fill('Demo owner');
  await page.getByLabel('Owner email').fill('demo-browser@example.test');
  await page.getByLabel('Owner password',{exact:true}).fill('demo-inbox-browser-password');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByLabel('Workspace name').fill('Real empty workspace');
  await page.getByRole('button',{name:'Review setup',exact:true}).click();
  await page.getByRole('button',{name:'Create workspace',exact:true}).click();
  await page.waitForURL(/\/projects\/[^/]+\/widget-settings$/);
  const originalId=new URL(page.url()).pathname.split('/')[2];
  await page.goto(`${runtime.origin}/projects/${originalId}/conversations`);
  await page.getByRole('button',{name:'Try a demo inbox',exact:true}).waitFor();
  await page.screenshot({path:join(evidence,'empty-invitation.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('#chat .main')).visibility==='hidden');
  await page.getByRole('button',{name:'Try a demo inbox',exact:true}).waitFor();
  await page.screenshot({path:join(evidence,'mobile-empty-invitation.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Try a demo inbox',exact:true}).click();
  await page.waitForURL(/\/projects\/demo-[^/]+\/conversations/);
  const demoId=new URL(page.url()).pathname.split('/')[2];
  assert.notEqual(demoId,originalId);
  const list=page.locator('.conversation-list-items');
  await list.getByText('Maya Chen (demo)',{exact:true}).waitFor();
  assert.equal(await list.locator('a').count(),6);
  await list.getByText('Maya Chen (demo)',{exact:true}).click();
  await page.getByText('Hi! I’m planning my first day hike. Would the Ridge 18 fit a rain jacket, lunch and two water bottles?',{exact:true}).waitFor();
  await page.reload();
  await page.locator('p').filter({hasText:'I’m 160 cm tall, so I’m also wondering whether the shoulder straps will adjust enough.'}).waitFor();
  await page.screenshot({path:join(evidence,'persisted-transcript.png'),fullPage:true});
  await list.getByText('Owen Reed (demo)',{exact:true}).click();
  const transcript=page.locator('#chat .main');
  const recentMessage='I’m back about the strap. In better light I can see a gap in the main stitching as well.';
  const groupedRun=transcript.locator('.transcript-message-run').filter({hasText:recentMessage});
  await groupedRun.getByText(recentMessage,{exact:true}).waitFor();
  assert.equal(await groupedRun.count(),1);
  assert.equal(await groupedRun.getByText('It’s about a centimetre wide, right where the strap joins the top of the pack.',{exact:true}).count(),1);
  assert.equal(await groupedRun.getByText('I haven’t tried to sew it or used it since we spoke.',{exact:true}).count(),1);
  const visits=transcript.locator('.transcript-actor-group').filter({hasText:recentMessage}).locator('.transcript-event-page-view-group');
  const toggle=visits.getByRole('button',{name:'(3 visits)',exact:true});
  assert.equal(await toggle.getAttribute('aria-expanded'),'false');
  await toggle.click();
  assert.equal(await visits.getByRole('button',{name:'(Hide visits)',exact:true}).getAttribute('aria-expanded'),'true');
  const visitLinks=visits.locator('.transcript-event-page-view-list .transcript-event-page-view-row a.pageview');
  assert.deepEqual(await visitLinks.evaluateAll(links=>links.map(link=>link.href)),[
    'https://northstar.example/help/repairs',
    'https://northstar.example/guides/checking-pack-straps',
    'https://northstar.example/help/returns',
  ]);
  await transcript.locator('.transcript-event-agent_assigned').filter({hasText:'Switched to human agent'}).waitFor();
  const note='Owner is handling the strap follow-up. Awaiting clarification on assessment packing requirements; no return, label, refund or replacement has been created.';
  await transcript.locator('.transcript-note-content').getByText(note,{exact:true}).waitFor();
  const olderMessage='I’ve noticed loose stitching where the left shoulder strap joins my Ridge 18.';
  assert.equal(await transcript.getByText(olderMessage,{exact:true}).count(),0);
  const olderHistory=transcript.locator('.bucket-group.closed > .bucket-group');
  await olderHistory.waitFor();
  await olderHistory.click();
  await transcript.locator('.bucket-group.expanded .transcript-message-run').getByText(olderMessage,{exact:true}).waitFor();
  await page.screenshot({path:join(evidence,'rich-transcript-expanded.png'),fullPage:true});
  await page.reload();
  await transcript.locator('.transcript-note-content').getByText(note,{exact:true}).waitFor();
  await transcript.locator('.transcript-event-agent_assigned').filter({hasText:'Switched to human agent'}).waitFor();
  await transcript.locator('.bucket-group.closed > .bucket-group').click();
  await transcript.locator('.bucket-group.expanded .transcript-message-run').getByText(olderMessage,{exact:true}).waitFor();
  await transcript.locator('.transcript-actor-group').filter({hasText:recentMessage}).getByRole('button',{name:'(3 visits)',exact:true}).click();
  await page.screenshot({path:join(evidence,'rich-transcript-reloaded.png'),fullPage:true});
  const check=await page.evaluate(async ({originalId,demoId})=>{
    const get=async path=>(await fetch(path)).json();
    return {original:await get(`/api/dashboard/projects/${originalId}/conversations/counts`),demo:await get(`/api/dashboard/projects/${demoId}/conversations/counts`),repeat:await (await fetch('/api/dashboard/demo-inbox',{method:'POST'})).json()};
  },{originalId,demoId});
  assert.equal(check.original.data.open+check.original.data.closed,0);
  assert.equal(check.demo.data.open,6);assert.equal(check.demo.data.closed,2);
  assert.equal(check.repeat.id,demoId);assert.equal(check.repeat.reused,true);
  assert.deepEqual(errors,[]);
  success=true;
  await writeFile(join(evidence,'result.json'),JSON.stringify({success,originalId,demoId,check,errors},null,2));
  console.log('Demo inbox browser passed: empty CTA, separate project, actual counts, transcript and reload, grouped messages, expanded visits, assignment, internal notes, earlier history, idempotent repeat, original unchanged. Evidence: '+evidence);
} finally {await browser.close();await runtime.close(success);}
