// Exercise the real standalone installer with isolated state; provider responses are test fixtures.
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, cp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { chromium } from 'playwright';
import { startInstaller } from '../scripts/installer/server.mjs';
import { derivePrefix } from '../scripts/installer/ui/model.mjs';
import { installerStepRegressions } from './helpers/installer-step-regressions.mjs';
import { sceneBackground } from './helpers/scene-background.mjs';
const root = await mkdtemp(join(tmpdir(), 'h2h-installer-presentation-'));
const source = resolve(import.meta.dirname, '..'), servers = [], errors = [], effects = [];
const evidence = process.env.H2H_EVIDENCE_DIR || '/tmp/h2h-grouped-installer';
const common = { name: 'Test workspace', allowedOrigin: 'https://example.test', primaryColor: '#12abef', ownerName: 'Test owner', email: 'owner@example.test', target: 'local', emailProvider: 'later' };
const wait = async predicate => { for (let i = 0; i < 100; i++) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 100)); } assert.fail('Timed out waiting for persisted state'); };
let browser;
async function fixture(name, options) {
  const directory = join(root, name);
  await mkdir(join(directory, 'scripts/installer'), { recursive: true });
  await mkdir(join(directory, 'public/setup'), { recursive: true });
  await cp(join(source, 'scripts/installer/ui'), join(directory, 'scripts/installer/ui'), { recursive: true });
  await cp(join(source, 'public/setup/ocean.webp'), join(directory, 'public/setup/ocean.webp'));
  const path = process.env.PATH;
  let installer;
  try { process.env.PATH = ''; installer = await startInstaller(directory, options); } finally { process.env.PATH = path; }
  servers.push(installer);
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  page.setDefaultTimeout(10000);
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/\/api\/(connect|start)$/.test(request.url())) effects.push(request.url()); });
  return { installer, page };
}
const visible = async (page, ids) => { for (const id of ids) assert.equal(await page.locator('#' + id).isVisible(), true, `${id} remains visible`); };
const shot = (page, name) => page.screenshot({ path: join(evidence, name + '.png'), fullPage: true });
try {
  await mkdir(evidence, { recursive: true });
  browser = await chromium.launch({ headless: true });
  const { page, installer } = await fixture('blank', { noPrefill: true });
  await page.goto(installer.origin); await page.locator('#name').waitFor();
  await visible(page, ['name', 'allowedOrigin', 'primaryColor', 'continue']);
  assert.deepEqual(await sceneBackground(page, '.scene'), { path: '/ocean.webp', status: 200, type: 'image/webp', width: 3072, height: 2048 });
  assert.equal(await page.locator('#ownerName').count(), 0);
  assert.equal(await page.locator('#approve').isVisible(), false);
  await shot(page, '01-workspace');
  for (const key of ['name', 'allowedOrigin', 'primaryColor']) { await page.locator('#' + key).fill(common[key]); await page.locator('#heading').click(); }
  await wait(() => installer.state.draft.primaryColor === common.primaryColor);
  await visible(page, ['name', 'allowedOrigin', 'primaryColor']);
  await page.locator('#continue').click(); await page.locator('#ownerName').waitFor();
  assert.equal(await page.locator('#email').getAttribute('type'), 'email');
  assert.equal(await page.locator('#password').getAttribute('autocomplete'), 'new-password');
  await page.locator('#email').fill('invalid-address');
  assert.equal(await page.locator('#email').evaluate(input => input.validity.typeMismatch), true);
  assert.equal(await page.locator('#continue').isDisabled(), true); await visible(page, ['ownerName', 'email', 'password']);
  for (const [key, value] of Object.entries({ ownerName: common.ownerName, email: common.email, password: 'test-only-long-password' })) { await page.locator('#' + key).fill(value); await page.locator('#heading').click(); }
  await visible(page, ['ownerName', 'email', 'password']);
  assert.equal(await page.locator('#visualInspiration').count(), 0);
  await shot(page, '02-account');
  await page.locator('#back').click(); await visible(page, ['name', 'allowedOrigin', 'primaryColor']);
  await page.locator('#continue').click();
  // The completed account group was already visited; advancing may skip to hosting.
  if (await page.locator('#ownerName').isVisible()) await page.locator('#continue').click();
  await page.locator('#target-local').waitFor();
  assert.equal(await page.locator('#fields [data-provider="github"]').count(), 1);
  await shot(page, '03-hosting-before-selection');
  await page.locator('#target-local').check(); await page.locator('#heading').click();
  await visible(page, ['target-local', 'target-remote']); await shot(page, '03-hosting');
  assert.equal(await page.locator('#continue').isDisabled(), true, 'Hosting also requires an email choice');
  await page.locator('#choice-later').waitFor();
  assert.equal(await page.locator('#heading').textContent(), 'Hosting & connections');
  await shot(page, '04-email-before-selection');
  await page.locator('#choice-now').check(); await page.locator('#choice-resend').check();
  assert.equal(await page.locator('#emailFrom').getAttribute('type'), 'email');
  assert.equal(await page.locator('#emailApiKey').getAttribute('type'), 'password');
  await page.locator('#choice-sendgrid').check();
  await page.locator('#emailFrom').fill('help@support.example.com');
  await page.locator('#emailApiKey').fill('sendgrid-fixture-key');
  await page.locator('#heading').click();
  await wait(() => installer.state.draft.emailProvider === 'sendgrid');
  assert.equal(await page.locator('#choice-sendgrid').isChecked(), true);
  assert.equal(await page.locator('#emailFrom').inputValue(), 'help@support.example.com');
  assert.equal(await page.locator('#emailApiKey').inputValue(), 'sendgrid-fixture-key');
  await page.locator('#choice-later').check(); await page.locator('#heading').click();
  await visible(page, ['target-local', 'target-remote', 'choice-now', 'choice-later']); await shot(page, '04-hosting-and-email');
  await page.setViewportSize({ width: 390, height: 844 }); await shot(page, '04-hosting-and-email-mobile');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.locator('#continue').click(); await page.locator('.ready-summary').waitFor();
  assert.equal(await page.locator('#approve').isEnabled(), true);
  assert.equal(await page.locator('#fields input, #fields select').count(), 0);
  assert.equal(await page.locator('#continue').isVisible(), false);
  assert.equal(await page.locator('.known-group').getByRole('heading', { name: 'Email', exact: true }).count(), 0, 'Email is part of Hosting & connections');
  assert.equal(await page.locator('.known-group').filter({ has: page.getByRole('heading', { name: 'Hosting & connections', exact: true }) }).getByText('Set up later', { exact: true }).count(), 1);
  await shot(page, '05-review');
  const edit = title => page.locator('.known-group').filter({ has: page.getByRole('heading', { name: title, exact: true }) }).getByRole('button', { name: /Edit/ }).first();
  await edit('Workspace').click(); await visible(page, ['name', 'allowedOrigin', 'primaryColor']);
  await page.locator('#name').fill('Renamed workspace'); await page.locator('#heading').click();
  await visible(page, ['name', 'allowedOrigin', 'primaryColor']);
  assert.equal(await page.locator('#approve').isVisible(), false);
  await page.locator('#continue').click(); await page.locator('.ready-summary').waitFor();
  await edit('Hosting & connections').click();
  const accountId = 'a'.repeat(32); let addressError = false;
  await page.route('**/api/address', async route => {
    const input = route.request().postDataJSON(), prefix = input.prefix || derivePrefix(input.name);
    await route.fulfill({ status: addressError ? 422 : 200, contentType: 'application/json', body: JSON.stringify(addressError ? { error: 'Test account needs a workers.dev subdomain.' } : { prefix, appOrigin: `https://${prefix}.fixture.workers.dev` }) });
  });
  await page.locator('#target-remote').check();
  installer.state.known.providers.cloudflare = { installed: true, authenticated: true, accounts: [{ id: accountId, name: 'Test account' }] };
  await wait(() => installer.state.draft.appOrigin === 'https://renamed-workspace.fixture.workers.dev');
  await visible(page, ['target-local', 'target-remote']);
  await shot(page, '06-cloudflare');
  await page.locator('#continue').click(); await page.locator('.ready-summary').waitFor();
  await edit('Workspace').click(); addressError = true;
  await page.locator('#name').fill('Address error'); await page.locator('#heading').click();
  await wait(() => installer.state.draft.name === 'Address error');
  await page.locator('#continue').click(); await page.getByRole('alert').filter({ hasText: 'Test account needs' }).waitFor();
  await shot(page, '07-address-error');
  addressError = false; await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await wait(() => installer.state.draft.appOrigin === 'https://address-error.fixture.workers.dev');
  await page.locator('#continue').click(); await page.locator('.ready-summary').waitFor();
  await page.setViewportSize({ width: 390, height: 844 }); await shot(page, '08-mobile');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await page.locator('[id]').evaluateAll(elements => new Set(elements.map(el => el.id)).size === elements.length), true);

  const partial = await fixture('partial', { answers: { name: common.name, allowedOrigin: common.allowedOrigin, primaryColor: common.primaryColor } });
  await partial.page.goto(partial.installer.origin); await partial.page.locator('#ownerName').waitFor();
  assert.equal(await partial.page.locator('#name').count(), 0, 'Initially complete workspace is skipped');
  // A late agent update fills the current group without changing the active step.
  Object.assign(partial.installer.state.draft, { ownerName: 'Agent owner', email: 'agent@example.test' });
  partial.installer.state.sources = { ...partial.installer.state.sources, ownerName: 'agent', email: 'agent' };
  partial.installer.state.lastUpdate = { revision: 100, source: 'agent', keys: ['ownerName', 'email'] };
  await wait(async () => await partial.page.locator('#ownerName').inputValue() === 'Agent owner');
  await visible(partial.page, ['ownerName', 'email', 'password']); await shot(partial.page, '09-agent-update');
  const passwordOnly = await fixture('password-only', { answers: common });
  await passwordOnly.page.goto(passwordOnly.installer.origin); await passwordOnly.page.locator('#password').waitFor();
  assert.equal(await passwordOnly.page.locator('#ownerName, #email').count(), 0, 'Provided account answers remain in the left summary');
  await passwordOnly.page.locator('#password').fill('test-only-long-password'); await passwordOnly.page.locator('#heading').click();
  await visible(passwordOnly.page, ['password', 'continue']);
  await passwordOnly.page.getByRole('button', { name: 'Edit Your account', exact: true }).click();
  await visible(passwordOnly.page, ['ownerName', 'email', 'password']);
  await shot(passwordOnly.page, '10-account-edit');
  const all = await fixture('all', { answers: common, secretInput: { password: 'test-only-long-password' } });
  await all.page.goto(all.installer.origin); await all.page.locator('.ready-summary').waitFor();
  assert.equal(await all.page.locator('#approve').isEnabled(), true, 'Optional GitHub does not block review');
  assert.equal(await all.page.locator('#fields input, #fields select').count(), 0);
  await shot(all.page, '11-all-known');
  await installerStepRegressions({ fixture, common, wait, visible, shot });
  assert.deepEqual(errors, []); assert.deepEqual(effects, [], 'No provider authentication or installation');
  console.log(`Installer grouped presentation passed; screenshots: ${evidence}`);
} finally { await browser?.close(); await Promise.all(servers.map(server => server.close())); await rm(root, { recursive: true, force: true }); }
