import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {randomBytes} from 'node:crypto';
const origin='http://localhost:8798';
const env=await readFile('.dev.vars','utf8');
const token=env.match(/^BOOTSTRAP_TOKEN=(.+)$/m)?.[1];
if(!token)throw new Error('Local bootstrap token absent');
const request=async(path,body,auth)=>{const r=await fetch(origin+path,{method:body?'POST':'GET',headers:{...(body?{'Content-Type':'application/json'}:{}),...(auth?{Authorization:'Bearer '+auth}:{})},body:body?JSON.stringify(body):undefined});const data=await r.json();if(!r.ok)throw new Error(path+' '+r.status+' '+JSON.stringify(data));return data;};
const email='native-browser-'+randomBytes(4).toString('hex')+'@example.test';
const password=randomBytes(18).toString('base64url');
const result=await request('/api/identity/bootstrap',{email,name:'Native browser verification',allowedOrigin:'http://localhost:8800'},token);
await request('/api/identity/password',{password},result.token);
const login=await request('/api/identity/login',{email,password});
const project=await request('/api/identity/projects/'+result.projectId,null,login.token);
await mkdir('.seed',{recursive:true});
await writeFile('.seed/browser-fixture.json',JSON.stringify({origin,email,password,token:login.token,projectId:result.projectId,userId:result.userId,widgetKey:project.widget_key}),{mode:0o600});
console.log(JSON.stringify({fixture:'.seed/browser-fixture.json',projectId:result.projectId}));
