import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import { chromium } from 'playwright';
import { createRuntime } from './helpers/emitted-runtime.mjs';
import { providerFixture } from './provider-helpers/fixture.mjs';
import { LocalRunner } from '../local-agent/lib/runner.mjs';
import { newConfig } from '../local-agent/lib/config.mjs';
import { checkAdditionalBrowserFailures } from './provider-helpers/browser-failures.mjs';
const evidence = resolve(process.env.H2H_EVIDENCE_DIR || 'test-results/provider-errors');
await mkdir(evidence, { recursive: true });
const runtime = await createRuntime();
let browser, fixture, success = false;
try {
  browser = await chromium.launch({ headless: true });
  const tenant = await runtime.seedTenant({ name: 'Provider errors', email: 'provider-error@native.test', allowedOrigin: runtime.origin });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  await context.addCookies([{ name: 'h2h_session', value: tenant.token, url: runtime.origin }]);
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const contact = randomUUID(), conversation = randomUUID(), project = tenant.projectId;
  await runtime.execute(`INSERT INTO contacts(id,project_id,name,email,created_at) VALUES('${contact}','${project}','Provider test customer','customer@native.test',1); INSERT INTO conversations(id,project_id,contact_id,revision,created_at,updated_at) VALUES('${conversation}','${project}','${contact}',0,1,1);`);
  const pairing = await context.request.post(runtime.origin + `/api/projects/${project}/local-agents/pairings`, { data: {} });
  assert.equal(pairing.status(), 200);
  const paired = await fetch(runtime.origin + '/api/local-agents/pair', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ code: (await pairing.json()).data.code, name: 'Error proof computer', provider: 'codex', capabilities: ['terminal'] }) });
  assert.equal(paired.status, 200); const device = (await paired.json()).data;
  fixture = await providerFixture({ beforeResponse: true, error: { message: 'Invalid schema for response_format. Missing attachment_ids. api_key=PRIVATE_API\nprompt: PRIVATE_CUSTOMER_CONTEXT', codexErrorInfo: { httpConnectionFailed: { httpStatusCode: 400 } }, additionalDetails: 'PRIVATE_DETAILS' }, stderr: 'Bearer PRIVATE_STDERR' });
  const config = newConfig({ server: runtime.origin, token: device.token, device: device.device, provider: 'codex', name: 'Error proof computer', workingDirectory: fixture.directory });
  const runner = new LocalRunner(config, { configPath: join(fixture.directory, 'connector.json') });
  await runner.run({ once: true });
  const location = runtime.origin + `/projects/${project}/conversations/${conversation}`;
  const openLocal = async () => {
    await page.goto(location);
    await page.locator('.conversation-assistant-toggle').waitFor();
    const show = page.getByRole('button', { name: 'Show conversation panel', exact: true });
    if (await show.isVisible()) await show.click();
    await page.locator('#conversation-assistant[aria-hidden=false]').waitFor();
    await page.getByRole('tab', { name: 'Local', exact: true }).click();
  };
  await openLocal();
  await page.locator('#delegation-device').selectOption(device.device.id);
  await page.locator('#delegation-mode').selectOption('resolve');
  await page.locator('#delegation-instructions').fill('Inspect the configuration; do not send a customer message.');
  await page.getByRole('button', { name: /^(Send|Queue) task$/ }).click();
  await page.locator('.delegation-job.is-queued').waitFor();
  await assert.rejects(runner.run({ once: true }), error => error.provider_error?.http_status === 400);
  await runner.run({ once: true });
  assert.equal((await readFile(fixture.path + '.calls', 'utf8')).trim(), 'turn/start');
  const jobsPath = runtime.origin + `/api/projects/${project}/conversations/${conversation}/delegations`;
  const response = await context.request.get(jobsPath); assert.equal(response.status(), 200);
  const jobs = (await response.json()).data; assert.equal(jobs.length, 1);
  assert.equal(jobs[0].status, 'failed'); assert.equal(jobs[0].result.provider_error.http_status, 400);
  for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport);
    await page.reload(); await openLocal();
    const failure = page.locator('.delegation-job.is-failed');
    await failure.locator('.delegation-job__provider-error').waitFor();
    const text = await failure.innerText();
    assert.match(text, /HTTP 400/); assert.match(text, /Missing attachment_ids/);
    assert.match(text, /Review the error before starting another task/);
    assert.doesNotMatch(text, /PRIVATE_/);
    assert.equal(await failure.getByRole('button', { name: /Send|Retry|Use/ }).count(), 0);
    await page.screenshot({ path: join(evidence, `provider-error-${viewport.width}.png`), fullPage: true });
  }
  const transcript = await context.request.get(runtime.origin + `/api/conversations/${conversation}/messages`);
  await checkAdditionalBrowserFailures({ runtime, context, page, jobsPath, device, fixture, runner, openLocal, evidence });
  const finalTranscript = await context.request.get(runtime.origin + `/api/conversations/${conversation}/messages`);
  assert.equal(finalTranscript.status(), 200); assert.equal((await finalTranscript.json()).messages.length, 0);
  assert.equal(transcript.status(), 200); assert.equal((await transcript.json()).messages.length, 0);
  const dbEvidence = await runtime.execute(`SELECT result FROM local_jobs WHERE id='${jobs[0].id}'; SELECT payload FROM local_events WHERE job_id='${jobs[0].id}'; SELECT COUNT(*) AS effects FROM local_result_effects WHERE job_id='${jobs[0].id}';`);
  assert.doesNotMatch(dbEvidence, /PRIVATE_/);
  assert.match(dbEvidence, /attachment_ids/);
  assert.deepEqual(errors, []);
  await writeFile(join(evidence, 'provider-error-receipt.json'), JSON.stringify({ passed: true, provider: 'test-only JSONL boundary', viewports: [1440, 390], job: jobs[0], assertions: ['paired native runner', 'HTTP 400 and excerpt durable in D1', 'operator reload', 'redacted DOM and events', 'one provider turn', 'no customer message or retry button'], dbEvidence }, null, 2));
  success = true;
  console.log('Provider error browser PASS: native pairing + runner + D1; HTTP 400 and redacted schema excerpt visible after reload at 1440/390; one attempt, no customer message. Provider fixture only.');
} finally { await fixture?.close(); await browser?.close(); await runtime.close(success); }
